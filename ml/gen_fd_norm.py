import json, re, sys, numpy as np, onnx
from onnx import numpy_helper
from pathlib import Path

M = Path("../models")
OUT = Path("../firmware_ref/fd_norm.h")
HER = Path("../firmware_ref/fd_preprocess.h")      # her current header, for cross-check

norm = json.load(open(M / "norm.json"))
mean = np.array(norm["mean"], dtype=np.float32)
std = np.array(norm["std"], dtype=np.float32)
assert len(mean) == len(std) == 4, "expected 4 channels"

# input scale / zero-point from the float-input INT8 model (QuantizeLinear on the input)
m = onnx.load(sys.argv[1] if len(sys.argv) > 1 else M / "tinycnn_int8.onnx")
g = m.graph
inp = g.input[0].name
q = next(n for n in g.node if n.op_type == "QuantizeLinear" and n.input[0] == inp)
inits = {i.name: numpy_helper.to_array(i) for i in g.initializer}
x_scale = float(inits[q.input[1]])
x_zp = int(inits[q.input[2]]) if len(q.input) > 2 and q.input[2] in inits else 0

def arr(a):
    return "{ " + ", ".join(f"{float(v):.9e}f" for v in a) + " }"

header = f"""/* fd_norm.h - GENERATED by ml/gen_fd_norm.py. Do not edit by hand.
 * Source: models/norm.json and the input QuantizeLinear of models/tinycnn_int8.onnx
 * Channel order: ax, ay, az, current
 */
#ifndef FD_NORM_H
#define FD_NORM_H

#define FD_X_SCALE  {x_scale:.9e}f
#define FD_X_ZP     {x_zp}

static const float FD_NORM_MEAN[4] = {arr(mean)};
static const float FD_NORM_STD [4] = {arr(std)};

#endif
"""
OUT.parent.mkdir(exist_ok=True)
OUT.write_text(header)
print(header)

# cross-check against the constants currently in her header
if HER.exists():
    txt = HER.read_text()
    def grab(name):
        s = re.search(name + r"\s*\[?\w*\]?\s*=?\s*\{?([^;}\n]+)", txt)
        return s.group(1) if s else None
    her_scale = re.search(r"#define FD_X_SCALE\s+([0-9.eE+-]+)f", txt)
    if her_scale:
        d = abs(float(her_scale.group(1)) - x_scale)
        print("X_SCALE vs her header, abs diff:", d, "(OK)" if d < 1e-7 else "(MISMATCH)")
    nums = re.findall(r"FD_NORM_(MEAN|STD)\s*\[FD_CHANNELS\]\s*=\s*\{([^}]*)\}", txt)
    for kind, body in nums:
        her = np.array([float(v.strip().rstrip("f")) for v in body.split(",")], dtype=np.float32)
        mine = mean if kind == "MEAN" else std
        print(f"NORM_{kind} max diff vs her header:", float(np.abs(her - mine).max()))